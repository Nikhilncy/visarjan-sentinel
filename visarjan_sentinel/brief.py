def _years(ranking: dict) -> list[int]:
    """Years covered by the data, read from the event labels, never configured."""
    return sorted({int(e.split()[-1]) for e in ranking["events"]})


def _years_text(years: list[int], lang: str) -> str:
    if len(years) == 1:
        return str(years[0])
    joiner = " और " if lang == "hi" else " and "
    return ", ".join(str(y) for y in years[:-1]) + joiner + str(years[-1])


def _num(v) -> str:
    if v is None:
        return "no numeric reading"
    return f"{v:g}"


def _event_label(e: dict, lang: str) -> str:
    if lang == "hi":
        return f"{FESTIVAL_HI[e['festival']]} {e['year']}"
    return f"{e['festival']} {e['year']}"


def _zero_do_citations(g: dict, lang: str) -> str:
    """Pages where this ghat printed DO = 0, grouped by report year."""
    by_year: dict[int, set[int]] = {}
    for e in g["events"]:
        if any(v == "0" for v in e["do_by_phase"].values()):
            by_year.setdefault(e["year"], set()).update(e["pages"])
    word = "रिपोर्ट" if lang == "hi" else "report"
    return "; ".join(
        f"{y} {word} " + ", ".join(f"p.{p}" for p in sorted(pages)) for y, pages in sorted(by_year.items())
    )


def _gap_lines(g: dict, lang: str) -> list[str]:
    lines = []
    for e in g["events"]:
        label = _event_label(e, lang)
        if not e["table_present"]:
            lines.append(
                f"{label} की तालिका {e['year']} की रिपोर्ट में नहीं है। यह अवधि बिना नमूने की है, स्वच्छ नहीं।"
                if lang == "hi"
                else f"No {label} table in the {e['year']} report. Unsampled, not clean."
            )
        elif e["not_sampled"]:
            phases = [p for p in PHASES if e["do_by_phase"].get(p) == "not sampled"]
            if lang == "hi":
                ph = f" ({', '.join(PHASE_HI[p] for p in phases)})" if phases else ""
                lines.append(f"{label}: {e['not_sampled']} परीक्षण नहीं किए गए{ph}। अनुपलब्ध, स्वच्छ नहीं।")
            else:
                ph = f" ({', '.join(phases)})" if phases else ""
                n = e["not_sampled"]
                lines.append(f"{label}: {n} reading{'s' if n != 1 else ''} not sampled{ph}. Missing, not clean.")
    if g["site_match_confidence"] != "high":
        lines.append(
            "स्थल-नाम मिलान की विश्वसनीयता मध्यम (MEDIUM) है। रिपोर्टों में गणेश तालिकाएँ इसे "
            "'Rani Kamlapati, Kamla Park, Murti Visarjan Kund' और दुर्गा तालिकाएँ 'Rani Kamlapati "
            "Visarjan Ghat (Lower Lake)' कहती हैं। ये दो अलग स्थान हो सकते हैं। यह विवरण एक संयुक्त "
            "प्रविष्टि रखता है और इन्हें एक ही स्थल नहीं मानता।"
            if lang == "hi"
            else "Site-name match is MEDIUM confidence. Ganesh tables say 'Rani Kamlapati, Kamla Park, "
            "Murti Visarjan Kund'; Durga tables say 'Rani Kamlapati Visarjan Ghat (Lower Lake)'. These "
            "may be two places. One combined entry is kept; they are not claimed to be the same site."
        )
    return lines


def _reason_hi(g: dict, limits: dict) -> str:
    pp = g["per_parameter"]
    parts = []
    do = pp.get("Dissolved oxygen")
    if do:
        s = (f"घुलित ऑक्सीजन (DO) के {do['numeric']} में से {do['exceedances']} परीक्षण श्रेणी B सीमा "
             f"(कम से कम {limits['Dissolved oxygen']['low']:g} mg/l) से नीचे")
        if g["zero_do_count"]:
            s += f", जिनमें {g['zero_do_count']} बार 0 mg/l ({_zero_do_citations(g, 'hi')})"
        elif g["min_do"] is not None and do["exceedances"]:
            s += f", न्यूनतम {g['min_do']:g} mg/l ({g['min_do_citation']})"
        parts.append(s + "।")
    bod = pp.get("BOD")
    if bod:
        parts.append(f"BOD के {bod['numeric']} में से {bod['exceedances']} परीक्षण श्रेणी B सीमा "
                     f"(अधिकतम {limits['BOD']['high']:g} mg/l) से ऊपर।")
    ph = pp.get("pH")
    if ph:
        parts.append(f"pH के {ph['numeric']} में से {ph['exceedances']} परीक्षण श्रेणी B सीमा "
                     f"({limits['pH']['low']:g} से {limits['pH']['high']:g}) से बाहर।")
    return " ".join(parts)


def _tier_reason_hi(g: dict) -> str:
    if g["tier"] == 1:
        return (f"स्तर 1: {g['do_below_tier1_count']} DO परीक्षण {TIER1_THRESHOLD_TEXT} से नीचे, "
                f"न्यूनतम {g['min_do']:g} mg/l ({g['min_do_citation']})।")
    return f"स्तर 2: कोई DO परीक्षण {TIER1_THRESHOLD_TEXT} से नीचे नहीं।"


def _evidence_line(g: dict, lang: str) -> str:
    pp = g["per_parameter"]
    bits = []
    for p, label in (("Dissolved oxygen", "DO"), ("BOD", "BOD"), ("pH", "pH")):
        t = pp.get(p)
        if not t:
            continue
        if t["exceedances"] == 0:
            bits.append(f"{label}: " + ("कोई परीक्षण सीमा से बाहर नहीं" if lang == "hi" else "no reading outside the limit"))
            continue
        unit = "" if p == "pH" else " mg/l"
        if p == "Dissolved oxygen":
            word = "न्यूनतम" if lang == "hi" else "lowest"
        elif p == "BOD":
            word = "अधिकतम" if lang == "hi" else "highest"
        else:
            word = "सीमा से सबसे दूर" if lang == "hi" else "furthest from range"
        bits.append(f"{label} {word} {t['worst_value']:g}{unit} ({t['worst_citation']})")
    return "; ".join(bits)


def _recent_low_do_sites(ranking: dict) -> list[str]:
    out = []
    for g in ranking["ghats"]:
        lo = g["recent"]["min_do"]
        if lo is not None and lo < ranking["limits"]["Dissolved oxygen"]["low"]:
            out.append(g["site"])
    return out


def _sources(lang: str, ctx: Context) -> list[str]:
    word = "पृष्ठ" if lang == "hi" else "pages"
    return [f"- {r.title}, {r.pages} {word}: {r.url}" for r in ctx.reports.values()]


def render_brief_en(ranking: dict, generated_on: dt.date, ctx: Context = CONTEXT) -> str:
    L = ranking["limits"]
    years = _years(ranking)
    y0, y1 = years[0], years[-1]
    tier1 = [g for g in ranking["ghats"] if g["tier"] == 1]
    recent_year = ranking["ghats"][0]["recent_year"]
    lines = [
        "# Visarjan Sentinel: Ghat follow-up brief",
        "",
        f"**For:** {ctx.organisation}, {ctx.event_name} planning ({ctx.event_date_en})  ",
        f"**Generated:** {_date_en(generated_on)}  ",
        f"**Data:** {ctx.source_label} {_years_text(years, 'en')} (Ganesh and Durga), "
        f"{len(ranking['ghats'])} Bhopal ghats  ",
        f"**Benchmark:** CPCB Class {ranking['water_class']}, {ranking['designated_use'].lower()}: "
        f"DO {L['Dissolved oxygen']['rule']}, BOD {L['BOD']['rule']}, pH {L['pH']['rule']}",
        "",
        f"> **Important.** This brief uses historical readings from {y0} to {y1}. The dataset ends in {y1} "
        f"and does not establish water conditions in {ctx.event_year}. It does not establish current water "
        "quality or safety at any ghat. It shows where follow-up testing and cleaning are most needed first.",
        "",
        "## 1. Highest follow-up priority (Tier 1)",
        "",
    ]
    if not tier1:
        lines.append("No ghat has a recorded dissolved-oxygen reading below "
                     f"{TIER1_THRESHOLD_TEXT}. See the full ranking below.")
    for g in tier1:
        lines += [
            f"### Rank {g['rank']}: {g['site']} ({g['water_body']})",
            f"- **Why:** {g['reason']}",
            f"- **Tier:** {g['tier_reason']}",
        ]
        gaps = _gap_lines(g, "en")
        if gaps:
            lines.append("- **Data gaps:** " + " ".join(gaps))
        lines.append("")
    lines += [
        "## 2. Full ranking",
        "",
        "| Rank | Tier | Ghat | Readings outside Class B limits | Lowest DO (mg/l) | Sampled coverage |",
        "|---|---|---|---|---|---|",
    ]
    for g in ranking["ghats"]:
        lines.append(
            f"| {g['rank']} | {g['tier']} | {g['site']} | {g['exceedances']} of {g['numeric_scored']} "
            f"| {_num(g['min_do'])} | {g['coverage']['sampled_share']:.0%} |"
        )
    lines += [
        "",
        "Readings outside limits are counted over all years, festivals and phases for DO, BOD and pH. "
        "Coverage is the share of expected readings that were actually sampled. It is shown separately "
        "and does not change the score.",
        "",
        "## 3. Key evidence",
        "",
    ]
    for g in ranking["ghats"]:
        lines.append(f"- **{g['site']}:** {_evidence_line(g, 'en')}.")
    lines += [
        "",
        "## 4. Recommended follow-up actions",
        "",
        "These are recommendations for the officer's consideration, not findings. The decision rests "
        "with the competent authority.",
        "",
    ]
    t1_names = ", ".join(g["site"] for g in tier1) or "none"
    low_recent = ", ".join(_recent_low_do_sites(ranking)) or "none"
    lines += [
        f"1. **Tier 1 ghats ({t1_names}):** consider pre-immersion sampling of DO, BOD and pH before "
        f"{ctx.event_date_en} and priority for cleaning and aeration resources.",
        f"2. **Ghats with DO below the limit in {recent_year} ({low_recent}):** consider DO monitoring "
        "during immersion.",
        "3. **All ghats in use:** sample all three phases (before, during, one week after) and include "
        "total coliform, so Class B compliance can be fully assessed.",
        "4. **Unsampled ghats or phases:** treat as unknown, not clean. Sample before immersion.",
        f"5. **Confirm which ghats will be in use in {ctx.event_year}** given the NGT restriction on immersion in the "
        f"Upper and Lower Lakes. This brief ranks all {len(ranking['ghats'])} ghats for which readings exist.",
        "",
        "## 5. Data gaps and limitations",
        "",
    ]
    for g in ranking["ghats"]:
        for line in _gap_lines(g, "en"):
            lines.append(f"- **{g['site']}:** {line}")
    for lim in ranking["limitations"]:
        lines.append(f"- {lim}")
    for note in ranking["notes"]:
        lines.append(f"- {note}")
    lines += [
        "",
        "## 6. Statement",
        "",
        f"Historical data cannot determine current water safety. The readings above were taken in "
        f"{_years_text(years, 'en')} and are reported against CPCB Class B limits only. This brief makes no claim "
        "about health effects or about present conditions at any ghat.",
        "",
        "## Sources",
        "",
        *_sources("en", ctx),
        "- CPCB water quality criteria: https://cpcb.gov.in/water-quality-criteria/",
        "",
    ]
    return "\n".join(lines)


