def render_brief(ranking: dict, lang: str, generated_on: dt.date | None = None,
                 ctx: Context = CONTEXT) -> str:
    """Render one brief. generated_on defaults to today, the actual generation date."""
    generated_on = generated_on or dt.date.today()
    if lang == "en":
        return render_brief_en(ranking, generated_on, ctx)
    if lang == "hi":
        return render_brief_hi(ranking, generated_on, ctx)
    raise ValueError(f"Unknown language {lang!r}; use 'en' or 'hi'")


def write_briefs(ranking: dict, out_dir: Path = OUTPUT_DIR, generated_on: dt.date | None = None,
                 ctx: Context = CONTEXT) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {}
    for lang in ("en", "hi"):
        p = out_dir / f"brief_{lang}.md"
        p.write_text(render_brief(ranking, lang, generated_on, ctx), encoding="utf-8")
        paths[lang] = p
    return paths


